"""Audit the competitive claims.

The page and the pitch both say "we differ from the category here". That column
is not a measurement, and saying it as if it were one is the cheapest way to lose
an auditor's trust. Every edge therefore has to declare:

  * our_proof  — a command or file in this repo that settles OUR side
  * competitor_status — observed / inferred / unverified, i.e. how much we know
                        about THEIR side

`observed` requires a source. Anything else must say it is not a measurement.

Usage:
    python benchmarks/edge_claims.py            # audit, print the table
    python benchmarks/edge_claims.py --write    # also rewrite Competitive_Edges.md
    python benchmarks/edge_claims.py --json

Exit 0 = every claim is labelled; non-zero = an unlabelled or unsupported claim.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "docs" / "methods" / "competitive_edges.json"
OUT = ROOT / "docs" / "methods" / "Competitive_Edges.md"
STATUSES = {"observed", "inferred", "unverified"}
FIELDS = {"id", "dimension", "our_claim", "our_proof", "competitor_status",
          "competitor_note", "risk"}


def load() -> list:
    return json.loads(DATA.read_text(encoding="utf-8"))["edges"]


def audit(edges: list) -> list:
    problems = []
    seen = set()
    for e in edges:
        missing = FIELDS - set(e)
        if missing:
            problems.append(f"{e.get('id', '?')}: missing fields {sorted(missing)}")
            continue
        if e["id"] in seen:
            problems.append(f"{e['id']}: duplicate id")
        seen.add(e["id"])
        if e["competitor_status"] not in STATUSES:
            problems.append(f"{e['id']}: status '{e['competitor_status']}' not in {sorted(STATUSES)}")
        proof = ROOT / e["our_proof"]
        if not proof.exists():
            problems.append(f"{e['id']}: our_proof '{e['our_proof']}' does not exist")
        if len(e["competitor_note"]) < 40:
            problems.append(f"{e['id']}: competitor_note under 40 chars — say what you actually know")
        if len(e["risk"]) < 30:
            problems.append(f"{e['id']}: risk under 30 chars — name the way this claim could be wrong")
        if e["competitor_status"] == "observed" and not e.get("source"):
            problems.append(f"{e['id']}: 'observed' without a source")
    return problems


def markdown(edges: list) -> str:
    lines = [
        "# Competitive edges — labelled, not asserted",
        "",
        "Generated by `benchmarks/edge_claims.py --write` from `competitive_edges.json`.",
        "Every row says how OUR claim is checked and how much we actually know about",
        "the other side. `inferred` and `unverified` mean we did not measure it;",
        "reading those rows as measurements is the one thing this file exists to prevent.",
        "",
        "| ID | Dimension | Our side (checkable) | Their side (how well we know) |",
        "|---|---|---|---|",
    ]
    for e in edges:
        lines.append(f"| {e['id']} | {e['dimension']} | {e['our_claim']} "
                     f"(`{e['our_proof']}`) | **{e['competitor_status']}** — {e['competitor_note']} |")
    obs = sum(1 for e in edges if e["competitor_status"] == "observed")
    inf = sum(1 for e in edges if e["competitor_status"] == "inferred")
    unv = sum(1 for e in edges if e["competitor_status"] == "unverified")
    lines += [
        "",
        f"**Provenance: {len(edges)} claims — observed {obs} / inferred {inf} / "
        f"unverified {unv}.** Only `observed` rows may be quoted as facts about others.",
        "",
        "## Ways this could be wrong",
        "",
    ]
    for e in edges:
        lines.append(f"- **{e['id']}** — {e['risk']}")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()

    edges = load()
    problems = audit(edges)
    if args.json:
        print(json.dumps({"edges": len(edges), "problems": problems}, indent=2))
    else:
        for e in edges:
            print(f"{e['id']:10s} {e['competitor_status']:10s} {e['dimension']}")
        obs = sum(1 for e in edges if e["competitor_status"] == "observed")
        inf = sum(1 for e in edges if e["competitor_status"] == "inferred")
        unv = sum(1 for e in edges if e["competitor_status"] == "unverified")
        print()
        print(f"edges      : {len(edges)}")
        print(f"provenance : observed {obs} / inferred {inf} / unverified {unv}")
        print(f"problems   : {len(problems)}")

    if problems:
        print()
        for p in problems:
            print(f"FAIL {p}")
        return 1

    if args.write:
        OUT.write_text(markdown(edges), encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
