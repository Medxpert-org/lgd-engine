"""What do I actually have to supply?

The engine judges a structured context, not prose. That makes the input contract
the first thing a stranger needs and the last thing anyone writes down. This file
derives it from the shipped cases instead of from the rule tables: a key that
appears in every case of a domain is required *for that domain*, and a key that
appears in some is optional with a stated consequence.

Derived, never authored: if a case gains a field, the table moves.

Usage:
    python benchmarks/input_contracts.py            # print the table
    python benchmarks/input_contracts.py --write    # rewrite docs/methods/Input_Contracts.md
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "methods" / "Input_Contracts.md"

DOMAINS = {
    "cases": ("Base schema (shared by all tables)", "510k"),
    "cases_postmarket": ("Post-market disposition", "postmarket"),
    "cases_pccp": ("FDA PCCP scope", "pccp"),
    "cases_mdr": ("EU MDR significance", "mdr"),
    "cases_nmpa": ("NMPA change route", "nmpa"),
    "cases_jurisdiction": ("Jurisdiction branch", "jurisdiction"),
}

META = {"case_id", "_desensitized_from", "expected_verdict", "expected_fda_verdict",
        "expected_nmpa_verdict", "expected_gate", "device_description"}

NOTE_BY_DOMAIN = {
    ("cases_nmpa", "device_class"): "1 = 备案 (filing), 2/3 = 注册 (registration). Class 1 uses a filing route; "
                                    "asking for 变更注册 on a class-1 device is the most common wrong answer.",
    ("cases_nmpa", "device_risk_class"): "Older name for device_class; either is accepted.",
    ("cases_nmpa", "regulatory_path"): "The route the applicant proposes, compared against requested_path.",
    ("cases_nmpa", "requested_path"): "The route being asked for now.",
    ("cases_nmpa", "change_fields"): "Changed attributes; split into textual vs domestic-site sets.",
    ("cases_nmpa", "has_registration_certificate"): "Without a certificate, a change cannot be a change *to* a registration.",
    ("cases_nmpa", "production_address_textual"): "True only for a textual correction; a real site move is not textual.",
    ("cases_nmpa", "device_site_domestic"): "Separates a domestic move from an overseas one.",
    ("cases_mdr", "intended_purpose_direction"): "'narrow' or 'widen'. Narrowing is not automatically significant.",
    ("cases_mdr", "correction_action_type"): "Type of corrective action taken.",
    ("cases_mdr", "authority_accepted"): "A competent authority already accepted it; blocks double-counting.",
    ("cases_pccp", "remains_se_to_predicate"): "Second cumulative condition of §515C(b).",
    ("cases_pccp", "pccp_modified_version_used_as_predicate"): "§515C(c) forbids this outright.",
}

NOTE_SHARED = {
    "evidence_sufficiency": "'sufficient' / 'insufficient'. A go without evidence is downgraded to hold.",
    "source_refs": "What the caller is relying on. Presence is checked; truth is not.",
    "change_type": "The change, in the vocabulary each table enumerates. Unlisted types return hold.",
    "jurisdiction": "Which regime's rules apply. One report never mixes two regimes.",
    "safety_effectiveness_assessed": "NMPA: the caller's conclusion on 安全有效. The engine takes the conclusion, not the argument.",
    "technical_docs_updated": "NMPA: whether technical documentation was updated with the change.",
    "recall_level": "NMPA: recall severity, if the change follows a recall.",
    "predicate_unchanged": "510(k): whether the predicate device itself is untouched.",
    "requires_submission": "510(k): whether the applicant believes a submission is required.",
    "safety_impact": "510(k): effect on safety or effectiveness.",
    "recall_class": "510(k) / post-market: I / II / III recall class.",
}


def _files(domain: str) -> list:
    return sorted((ROOT / "demo1" / domain).glob("*.json"))


def _analyse(domain: str) -> tuple:
    files = _files(domain)
    counts = {}
    for f in files:
        for k in json.loads(f.read_text(encoding="utf-8")).keys():
            counts[k] = counts.get(k, 0) + 1
    required = [k for k, n in counts.items() if n == len(files) and k not in META]
    optional = [k for k, n in counts.items() if n < len(files) and k not in META]
    return files, required, optional


def build() -> str:
    lines = [
        "# Input contracts — what you have to supply",
        "",
        "Generated by `benchmarks/input_contracts.py --write` from the shipped cases.",
        "A required key appears in **every** case of that domain; an optional key appears",
        "in some. The five generic cases carry the full schema, so a key you see marked",
        "required under a specific table but not under `Base schema` is still accepted —",
        "the tables share a vocabulary. This is a statement about the cases, not about the",
        "judges' internals: if a case gains a field, this table moves with it.",
        "",
        "Verdict semantics are unchanged: exit code 0 = go, 1 = hold, 2 = reject,",
        "3 = tool error, 64 = usage. Anything outside the enumerated categories returns `hold`.",
        "",
    ]
    for domain, (label, cli_domain) in DOMAINS.items():
        files, required, optional = _analyse(domain)
        lines += [f"## {label}", "",
                  f"`python -m lgd_engine.cli --all demo1/{domain} --domain {cli_domain}` "
                  f"— {len(files)} cases", "",
                  "| key | status | note |", "|---|---|---|"]

        def _note(k: str) -> str:
            return NOTE_BY_DOMAIN.get((domain, k)) or NOTE_SHARED.get(k) or "—"

        for k in sorted(required):
            lines.append(f"| `{k}` | **required** | {_note(k)} |")
        for k in sorted(optional):
            lines.append(f"| `{k}` | optional | {_note(k)} |")
        lines.append("")

    lines += [
        "## What this table does not tell you",
        "",
        "- Whether your values are **true**. The engine checks presence and internal",
        "  consistency, not that a certificate exists or that a change really is textual.",
        "- Which of two plausible values is correct. That is the regulatory judgement",
        "  the caller brings; the engine only applies the consequence once it is supplied.",
        "- Anything about the nine uncoded clauses in `coverage_gaps.json`.",
        "",
        "If a required key is missing, the judge treats the field as unknown and the",
        "result is `hold` rather than a guess — that behaviour is pinned by the L2 test.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = build()
    if "--write" in sys.argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
