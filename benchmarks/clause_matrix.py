"""Clause matrix: every shipped rule must name the provision it encodes.

Why this exists: a judge that says "significant" without naming the clause is
indistinguishable from a model's opinion. This script turns "rule → provision"
into a table a stranger can audit, and exits non-zero when the mapping is
incomplete in either direction:

  * a rule shipped in a judge but absent from `judges/basis.py`
  * an entry in `basis.py` that names no shipped rule (dead authority)

Usage:
    python benchmarks/clause_matrix.py            # print table, exit 0/1
    python benchmarks/clause_matrix.py --write    # regenerate docs/methods/Clause_Matrix.md
"""
from __future__ import annotations

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from lgd_engine.judges.basis import CLAUSE_BASIS, is_law, shipped_rules  # noqa: E402

OUT = ROOT / "docs" / "methods" / "Clause_Matrix.md"


def main(argv: list[str]) -> int:
    rules = shipped_rules()
    missing = [r for r in rules if not CLAUSE_BASIS.get(r)]
    dead = [r for r in CLAUSE_BASIS if r not in rules]
    law = sum(1 for r in rules if is_law(CLAUSE_BASIS.get(r, "")))
    doctrine = len(rules) - law

    print(f"rules shipped: {len(rules)}")
    print(f"with a basis : {len(rules) - len(missing)}  (LAW {law} / DOCTRINE {doctrine})")
    for r in missing:
        print(f"  MISSING BASIS  {rules[r]}: {r}")
    for r in dead:
        print(f"  DEAD ENTRY     {r}")

    if argv[1:2] == ["--write"]:
        lines = [
            "# Clause matrix — every rule names its provision",
            "",
            "Generated by `benchmarks/clause_matrix.py`. The mapping lives in",
            "`lgd_engine/judges/basis.py`; this table is the readable form of it.",
            "",
            "`LAW` = a provision whose text was read (statute, regulation, MDCG/CAMD",
            "notice, FDA guidance). `DOCTRINE` = a house rule that is not itself a legal",
            "obligation, declared as such so it cannot pass for law.",
            "",
            f"**{len(rules)} rules · {law} LAW · {doctrine} DOCTRINE · 0 unbased**",
            "",
            "| Judge | Rule | Basis |",
            "|---|---|---|",
        ]
        for judge, rid in sorted(rules.items(), key=lambda kv: (kv[1], kv[0])):
            lines.append(f"| `{judge}` | `{rid}` | {CLAUSE_BASIS.get(rid, '—')} |")
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")

    return 0 if not missing and not dead else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
